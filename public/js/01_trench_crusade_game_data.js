/** Goetic Powers of a Sin as upgrades: Praetor 2 (1 in Wrath), Sorcerer 3, Hell Knight 1 + Blood Magic. */
function courtSinUpgrades(sin) {
  const perModel = { praetor: sin === 'wrath' ? 1 : 2, sorcerer: 3, 'hell-knights': 1 };
  const out = [];
  for (const [name, cost, kind, who, limit, effect, extra] of COURT_SIN_POWERS[sin]) {
    const units = who === 'ps' ? ['praetor','sorcerer'] : ['praetor','sorcerer','hell-knights'];
    for (const unitId of units) {
      out.push({ unitId, upgrade: Object.assign({
        id: 'gp-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''),
        name, cost, currency: '👑', addsAbilities: [name],
        perModelGroup: 'goetic', perModelMax: perModel[unitId],
        note: 'Goetic ' + kind + (who === 'ps' ? ' · Praetors & Sorcerers only' : ' · ELITE only') +
              (limit ? ' · Limit: ' + limit : '') + '. ' + effect,
      }, limit ? { maxPerWarband: limit } : {}, extra || {}) });
    }
  }
  return out;
}

